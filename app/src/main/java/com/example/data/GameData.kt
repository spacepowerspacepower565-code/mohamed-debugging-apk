        val baseLevel = if (levelId <= wordLevels.size) {
            wordLevels[staticIndex]
        } else {
            // Procedural generator
            val word1 = extraWords[(levelId * 3) % extraWords.size]
            val word2 = extraWords[(levelId * 7 + 1) % extraWords.size]
            val word3 = extraWords[(levelId * 11 + 2) % extraWords.size]
            val uniqueWords = listOf(word1.first, word2.first, word3.first).distinct()
            WordSwipeLevel(
                id = levelId,
                theme = "تحدي الكلمات رقم $levelId",
                wordsToFind = uniqueWords,
                gridLetters = emptyList()
            )
        }

        // Generate contiguous letters in the 4x4 grid dynamically to guarantee adjacent paths, cached per level.
        val continuousGrid = wordGridCache.getOrPut(levelId) {
            generateContinuousGrid(baseLevel.wordsToFind)
        }
        return baseLevel.copy(gridLetters = continuousGrid)
    }

    // Backtracking grid letter generator to place words in contiguous adjacent pathways
    private fun generateContinuousGrid(words: List<String>): List<String> {
        val grid = Array(16) { "" }
        var callCount = 0
        val maxCalls = 1500

        fun placeWord(wordIndex: Int, letterIndex: Int, currentCell: Int): Boolean {
            callCount++
            if (callCount > maxCalls) return false
            if (wordIndex >= words.size) return true
            val word = words[wordIndex]
            
            // If we completed this word, transition to the next word
            if (letterIndex >= word.length) {
                if (wordIndex + 1 >= words.size) return true
                val nextStartLetter = words[wordIndex + 1].first().toString()
                
                // 1. Try starting the next word from any cell that already contains the starting letter of the next word!
                val existingStartCells = grid.indices.filter { grid[it] == nextStartLetter }
                for (startCell in existingStartCells.shuffled()) {
                    if (placeWord(wordIndex + 1, 1, startCell)) {
                        return true
                    }
                }
                
                // 2. Otherwise try starting the next word from any empty cell
                val emptyCells = grid.indices.filter { grid[it].isEmpty() }
                if (emptyCells.isEmpty()) return false
                
                for (startCell in emptyCells.shuffled()) {
                    grid[startCell] = nextStartLetter
                    if (placeWord(wordIndex + 1, 1, startCell)) {
                        return true
                    }
                    grid[startCell] = ""
                }
                return false
            }

            val letter = word[letterIndex].toString()
            val r = currentCell / 4
            val c = currentCell % 4

            // Find all 8-directional neighbors (either empty OR matching the target letter to allow overlap!)
            val neighbors = mutableListOf<Int>()
            for (dr in -1..1) {
                for (dc in -1..1) {
                    if (dr == 0 && dc == 0) continue
                    val nr = r + dr
                    val nc = c + dc
                    if (nr in 0..3 && nc in 0..3) {
                        val nIndex = nr * 4 + nc
                        if (grid[nIndex].isEmpty() || grid[nIndex] == letter) {
                            neighbors.add(nIndex)
                        }
                    }
                }
            }

            // Try drawing the path through shuffled adjacent cells
            for (nextCell in neighbors.shuffled()) {
                val wasEmpty = grid[nextCell].isEmpty()
                if (wasEmpty) {
                    grid[nextCell] = letter
                }
                if (placeWord(wordIndex, letterIndex + 1, nextCell)) {
                    return true
                }
                if (wasEmpty) {
                    grid[nextCell] = "" // backtrack
                }
            }
            return false
        }

        // Start path placement for the first word
        var success = false
        val startCells = (0..15).toList().shuffled()
        for (startCell in startCells) {
            grid[startCell] = words[0].first().toString()
            if (placeWord(0, 1, startCell)) {
                success = true
                break
            }
            grid[startCell] = ""
        }

        // Fallback if placement failed (or hit maxCalls limit), populate unique letters of words on empty slots, then random
        if (!success) {
            var letterIndex = 0
            val allCombinedLetters = words.flatMap { it.chunked(1) }.distinct()
            for (i in 0..15) {
                if (grid[i].isEmpty() && letterIndex < allCombinedLetters.size) {
                    grid[i] = allCombinedLetters[letterIndex++]
                }
            }
        }

        // Fill remaining empty tiles with random vibrant Arabic alphabets
        val alphabets = listOf("أ", "ب", "ت", "ث", "ج", "ح", "خ", "د", "ذ", "ر", "ز", "س", "ش", "ص", "ض", "ط", "ظ", "ع", "غ", "ف", "ق", "ك", "ل", "م", "ن", "هـ", "و", "ي")
        for (i in grid.indices) {
            if (grid[i].isEmpty()) {
                grid[i] = alphabets.random()
            }
        }
        return grid.toList()
    }
}

